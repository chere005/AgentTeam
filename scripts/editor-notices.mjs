import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
export function editorNotices() {
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const lock = JSON.parse(
    readFileSync(join(root, "package-lock.json"), "utf8"),
  );
  const seen = new Set();
  const visit = (name, from = "") => {
    let parent = from,
      key;
    for (;;) {
      key = `${parent ? parent + "/" : ""}node_modules/${name}`;
      if (lock.packages[key]) break;
      if (!parent) throw new Error(`Missing editor dependency ${name}`);
      parent = parent.includes("/node_modules/")
        ? parent.slice(0, parent.lastIndexOf("/node_modules/"))
        : "";
    }
    if (seen.has(key)) return;
    seen.add(key);
    for (const dep of Object.keys(lock.packages[key].dependencies ?? {}))
      visit(dep, key);
  };
  for (const name of Object.keys(pkg.dependencies).filter(
    (name) =>
      name === "codemirror" ||
      name.startsWith("@codemirror/") ||
      name.startsWith("@lezer/"),
  ))
    visit(name);
  return (
    "CodeMirror editor and transitive dependency licenses\nGenerated by node scripts/editor-notices.mjs --write\n\n" +
    [...seen]
      .sort()
      .map((key) => {
        const entry = JSON.parse(
          readFileSync(join(root, key, "package.json"), "utf8"),
        );
        const filename = [
          "LICENSE",
          "LICENSE.md",
          "LICENSE.txt",
          "LICENCE",
        ].find((name) => existsSync(join(root, key, name)));
        if (!filename) throw new Error(`Missing license for ${entry.name}`);
        return `${entry.name} ${entry.version}\nhttps://www.npmjs.com/package/${entry.name}/v/${entry.version}\n\n${readFileSync(join(root, key, filename), "utf8").trim()}\n`;
      })
      .join("\n----------------------------------------\n\n")
  );
}
if (process.argv.includes("--write"))
  writeFileSync(
    join(root, "assets/licenses/EDITOR-LICENSES.txt"),
    editorNotices(),
  );
